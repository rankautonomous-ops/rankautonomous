process.env.NODE_ENV = 'test';

import assert from 'assert';
import prisma from '../lib/database';
import { setAiProvider, IAiProvider, AiCompletionOptions } from '../services/aiProvider';
import { generateContentPlan } from '../services/contentCalendar/generatePlan';
import { executeDailyContentGeneration } from '../trigger/dailyContentGeneration';
import { executeDailyContentGenerationCron } from '../trigger/dailyContentGenerationCron';

const TEST_USER_ID = 'test-calendar-user';
const TEST_AUTH_ID = 'test-calendar-auth';
const TEST_WEBSITE_ID = 'test-calendar-site';
const TEST_DISABLED_SITE_ID = 'test-calendar-disabled-site';

class MockCalendarAiProvider implements IAiProvider {
  async generateCompletion(opts: AiCompletionOptions): Promise<string> {
    const prompt = opts.systemPrompt + opts.userPrompt;

    if (prompt.includes('create a content plan') || prompt.includes('SEO content planner')) {
      return JSON.stringify([
        {
          topic: "Autonomous SEO Playbook 2026",
          targetKeyword: "autonomous seo playbook",
          searchIntent: "INFORMATIONAL",
          wordCount: 1500
        },
        {
          topic: "Internal Linking Automation Guide",
          targetKeyword: "internal linking automation",
          searchIntent: "COMMERCIAL",
          wordCount: 1800
        },
        {
          topic: "Duplicate Topic To Skip",
          targetKeyword: "existing keyword",
          searchIntent: "INFORMATIONAL",
          wordCount: 1200
        }
      ]);
    }

    if (prompt.includes('FAIL_TRIGGER_GEN')) {
      throw new Error('AI Provider Service Unavailable 503');
    }

    return JSON.stringify({
      title: "Scheduled Article Title",
      metaDescription: "Automated article meta description",
      slug: "scheduled-article-title",
      headings: ["H2: Introduction", "H3: Key Takeaways"],
      content: "<p>This is automated content generated by the scheduled daily task.</p>",
      internalLinks: [],
      imageSuggestions: ["Cover Image"],
      cta: "Start Free Trial"
    });
  }
}

async function setup() {
  await teardown();

  await prisma.user.create({
    data: {
      id: TEST_USER_ID,
      supabaseAuthId: TEST_AUTH_ID,
      email: 'calendar-test@example.com',
      role: 'CUSTOMER'
    }
  });

  await prisma.subscription.create({
    data: {
      userId: TEST_USER_ID,
      status: 'active',
      plan: 'pro',
      interval: 'month'
    }
  });

  await prisma.website.create({
    data: {
      id: TEST_WEBSITE_ID,
      userId: TEST_USER_ID,
      url: 'https://calendar-test.com',
      name: 'Calendar Test Site',
      contentAutomationEnabled: true
    }
  });

  await prisma.website.create({
    data: {
      id: TEST_DISABLED_SITE_ID,
      userId: TEST_USER_ID,
      url: 'https://disabled-site.com',
      name: 'Disabled Site',
      contentAutomationEnabled: false
    }
  });

  // Create keywords for content planner
  await prisma.keyword.create({
    data: {
      websiteId: TEST_WEBSITE_ID,
      keyword: 'autonomous seo playbook',
      normalizedKeyword: 'autonomous seo playbook',
      status: 'ACTIVE',
      opportunityScore: 88,
      searchVolume: 1200,
      difficulty: 35
    }
  });

  await prisma.keyword.create({
    data: {
      websiteId: TEST_WEBSITE_ID,
      keyword: 'internal linking automation',
      normalizedKeyword: 'internal linking automation',
      status: 'ACTIVE',
      opportunityScore: 75,
      searchVolume: 900,
      difficulty: 40
    }
  });

  // Pre-existing article targeting 'existing keyword' to test duplicate prevention
  await prisma.article.create({
    data: {
      websiteId: TEST_WEBSITE_ID,
      topic: 'Pre-existing Article',
      title: 'Pre-existing Article',
      primaryKeyword: 'existing keyword',
      status: 'IDEA',
      content: '<p>Existing content</p>'
    }
  });
}

async function teardown() {
  await prisma.aiJob.deleteMany({ where: { userId: TEST_USER_ID } });
  await prisma.article.deleteMany({ where: { websiteId: { in: [TEST_WEBSITE_ID, TEST_DISABLED_SITE_ID] } } });
  await prisma.keyword.deleteMany({ where: { websiteId: { in: [TEST_WEBSITE_ID, TEST_DISABLED_SITE_ID] } } });
  await prisma.website.deleteMany({ where: { id: { in: [TEST_WEBSITE_ID, TEST_DISABLED_SITE_ID] } } });
  await prisma.subscription.deleteMany({ where: { userId: TEST_USER_ID } });
  await prisma.user.deleteMany({ where: { id: TEST_USER_ID } });
}

async function runCalendarTests() {
  console.log('==================================================');
  console.log('RUNNING CONTENT CALENDAR & AUTOMATION TESTS');
  console.log('==================================================\n');

  let passed = 0;
  let failed = 0;

  function recordPass(msg: string) {
    console.log(`PASS: ${msg}`);
    passed++;
  }

  function recordFail(msg: string, err: any) {
    console.error(`FAIL: ${msg}`, err);
    failed++;
  }

  setAiProvider(new MockCalendarAiProvider());
  await setup();

  try {
    // -------------------------------------------------------------
    // 1. Content Plan Generation & Duplicate Keyword Prevention
    // -------------------------------------------------------------
    const plannedArticles = await generateContentPlan({
      websiteId: TEST_WEBSITE_ID,
      numberOfArticles: 3
    });

    assert.ok(Array.isArray(plannedArticles), 'Plan should return array of articles');
    assert.equal(plannedArticles.length, 2, 'Should create 2 articles and filter out the duplicate "existing keyword"');
    
    for (const art of plannedArticles) {
      assert.equal(art.status, 'PLANNED', 'Planned article status should be PLANNED');
      assert.ok(art.scheduledAt, 'Article must have scheduledAt date');
      assert.ok(art.scheduledAt > new Date(), 'Scheduled date should be in the future');
    }
    recordPass('1. Content plan generates articles and filters duplicate keywords');

    // -------------------------------------------------------------
    // 2. Scheduled Generation: Website Not Found
    // -------------------------------------------------------------
    const notFoundResult = await executeDailyContentGeneration({ websiteId: 'non-existent-site-id' });
    assert.equal(notFoundResult.success, false);
    assert.equal(notFoundResult.message, 'Website not found');
    recordPass('2. Daily content generation returns safe error for missing website');

    // -------------------------------------------------------------
    // 3. Scheduled Generation: Automation Disabled Website
    // -------------------------------------------------------------
    const disabledResult = await executeDailyContentGeneration({ websiteId: TEST_DISABLED_SITE_ID });
    assert.equal(disabledResult.success, false);
    assert.equal(disabledResult.message, 'Automation disabled');
    recordPass('3. Daily content generation skips website when contentAutomationEnabled is false');

    // -------------------------------------------------------------
    // 4. Scheduled Generation: No Eligible Articles (all in the future)
    // -------------------------------------------------------------
    const noEligibleResult = await executeDailyContentGeneration({ websiteId: TEST_WEBSITE_ID });
    assert.equal(noEligibleResult.success, false);
    assert.equal(noEligibleResult.message, 'No eligible articles');
    recordPass('4. Daily content generation skips when all planned articles are scheduled in the future');

    // -------------------------------------------------------------
    // 5. Controlled Scheduled Generation Run on Eligible Article
    // -------------------------------------------------------------
    // Mark one of the planned articles as due now (scheduledAt in the past)
    const targetArticle = plannedArticles[0];
    const pastDate = new Date(Date.now() - 3600000); // 1 hour ago
    await prisma.article.update({
      where: { id: targetArticle.id },
      data: { scheduledAt: pastDate }
    });

    const runResult = await executeDailyContentGeneration({ websiteId: TEST_WEBSITE_ID });
    assert.equal(runResult.success, true);
    assert.equal(runResult.articleId, targetArticle.id);

    const generatedArticle = await prisma.article.findUnique({ where: { id: targetArticle.id } });
    assert.equal(generatedArticle?.status, 'DRAFT', 'Article transitions from PLANNED to DRAFT upon successful generation');
    assert.ok(generatedArticle?.content?.includes('automated content'), 'Content is persisted into article');
    assert.ok(generatedArticle?.title?.length! > 0, 'Title is persisted');
    recordPass('5. Daily content generation successfully executes eligible scheduled article');

    // -------------------------------------------------------------
    // 6. Duplicate Prevention: Daily Limit (1 article per day)
    // -------------------------------------------------------------
    // Make the second article also eligible for today
    const secondArticle = plannedArticles[1];
    await prisma.article.update({
      where: { id: secondArticle.id },
      data: { scheduledAt: pastDate }
    });

    const secondRunResult = await executeDailyContentGeneration({ websiteId: TEST_WEBSITE_ID });
    assert.equal(secondRunResult.success, false);
    assert.equal(secondRunResult.message, 'Daily limit reached');

    const secondArtCheck = await prisma.article.findUnique({ where: { id: secondArticle.id } });
    assert.equal(secondArtCheck?.status, 'PLANNED', 'Second article remains PLANNED and is not duplicated');
    recordPass('6. Daily content generation enforces 1-article-per-day limit and prevents duplicate runs');

    // -------------------------------------------------------------
    // 7. Concurrency Conflict Handling
    // -------------------------------------------------------------
    // Create an article with status already GENERATING
    const concurrentArt = await prisma.article.create({
      data: {
        websiteId: TEST_WEBSITE_ID,
        topic: 'Concurrent Article',
        title: 'Concurrent Article',
        primaryKeyword: 'concurrent keyword',
        status: 'GENERATING',
        scheduledAt: pastDate
      }
    });

    // Simulate update failure on status
    const conflictResult = await executeDailyContentGeneration({ websiteId: TEST_WEBSITE_ID });
    assert.equal(conflictResult.success, false);
    assert.equal(conflictResult.message, 'Daily limit reached');
    recordPass('7. Concurrency and status check protects against unexpected execution');

    // -------------------------------------------------------------
    // 8. Error Handling: AI Generation Failure Transitions Article to FAILED
    // -------------------------------------------------------------
    // Create a new website where no articles were generated today to test error handling
    const errorSiteId = 'test-calendar-error-site';
    await prisma.website.create({
      data: {
        id: errorSiteId,
        userId: TEST_USER_ID,
        url: 'https://error-site.com',
        name: 'Error Test Site',
        contentAutomationEnabled: true
      }
    });

    const failingArticle = await prisma.article.create({
      data: {
        websiteId: errorSiteId,
        topic: 'FAIL_TRIGGER_GEN',
        title: 'Failing Article',
        primaryKeyword: 'fail trigger',
        status: 'PLANNED',
        scheduledAt: pastDate
      }
    });

    let threw = false;
    try {
      await executeDailyContentGeneration({ websiteId: errorSiteId });
    } catch (e: any) {
      threw = true;
      assert.ok(e.message.includes('503'));
    }
    assert.equal(threw, true, 'Execution should throw error so Trigger.dev runtime can orchestrate retries');

    const failedArtCheck = await prisma.article.findUnique({ where: { id: failingArticle.id } });
    assert.equal(failedArtCheck?.status, 'FAILED', 'Article status transitions to FAILED when generation fails');
    recordPass('8. AI failure transitions article to FAILED and throws for Trigger retry backoff');

    // Clean up error site
    await prisma.aiJob.deleteMany({ where: { websiteId: errorSiteId } });
    await prisma.article.deleteMany({ where: { websiteId: errorSiteId } });
    await prisma.website.delete({ where: { id: errorSiteId } });

    // -------------------------------------------------------------
    // 9. Daily Content Generation CRON Scheduler Execution
    // -------------------------------------------------------------
    const triggeredSites: string[] = [];
    const cronResult = await executeDailyContentGenerationCron(async (payload) => {
      triggeredSites.push(payload.websiteId);
      return { runId: 'mock-cron-run-' + payload.websiteId };
    });

    assert.equal(cronResult.success, true);
    assert.ok(cronResult.websitesFound >= 1, 'Should find at least 1 automation-enabled website');
    assert.ok(triggeredSites.includes(TEST_WEBSITE_ID), 'Enabled website was triggered');
    assert.ok(!triggeredSites.includes(TEST_DISABLED_SITE_ID), 'Disabled website was NOT triggered');
    recordPass('9. Daily CRON task triggers only automation-enabled websites and excludes disabled sites');

    // -------------------------------------------------------------
    // 10. CRON Resilience to Individual Site Dispatch Failures
    // -------------------------------------------------------------
    let attemptCount = 0;
    const resilientCronResult = await executeDailyContentGenerationCron(async (payload) => {
      attemptCount++;
      if (payload.websiteId === TEST_WEBSITE_ID) {
        throw new Error('Transient network error dispatching Trigger task');
      }
      return { runId: 'ok' };
    });

    assert.equal(resilientCronResult.success, true, 'CRON task completes successfully despite individual failure');
    assert.ok(attemptCount >= 1, 'All sites were attempted');
    recordPass('10. Daily CRON handles individual site trigger errors gracefully without aborting');

  } catch (err) {
    recordFail('Content Calendar Test Suite Failure', err);
  } finally {
    await teardown();
    setAiProvider(null);
    await prisma.$disconnect();

    console.log('\n==================================================');
    console.log(`SUMMARY: ${passed} Passed, ${failed} Failed`);
    console.log('==================================================\n');

    if (failed > 0) {
      process.exit(1);
    }
  }
}

runCalendarTests();
